// Regenerates the web demo's copies of the Android scam dictionaries and UI strings:
//   android/.../security/ScamPhrases.kt  → web/src/engine/phrases.js
//   android/.../res/values*/strings.xml  → web/src/strings.js
// Run from the repository root or web/: node web/scripts/sync-from-android.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const android = join(web, '..', 'android', 'app', 'src', 'main');
const header = (source) => `// GENERATED by web/scripts/sync-from-android.mjs from ${source}. Do not edit by hand.\n`;

function kotlinStrings(block) {
  return [...block.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => JSON.parse(`"${m[1]}"`));
}

function phrases() {
  const src = readFileSync(join(android, 'java/io/cybershield/app/security/ScamPhrases.kt'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '');
  const sections = {};
  const starts = [...src.matchAll(/val (\w+)(?:\s*:[^=]+)?\s*=\s*(mapOf|listOf)\(/g)];
  starts.forEach((m, i) => {
    const body = src.slice(m.index + m[0].length, i + 1 < starts.length ? starts[i + 1].index : src.length);
    if (m[2] === 'listOf') {
      sections[m[1]] = kotlinStrings(body);
    } else {
      const map = {};
      const entries = [...body.matchAll(/FindingCode\.(\w+) to listOf\(/g)];
      entries.forEach((e, j) => {
        const end = j + 1 < entries.length ? entries[j + 1].index : body.length;
        map[e[1]] = kotlinStrings(body.slice(e.index + e[0].length, end));
      });
      sections[m[1]] = map;
    }
  });
  for (const name of ['english', 'hinglish', 'hindi', 'marathi', 'secrets', 'requestVerbs', 'safetyNotices']) {
    if (!sections[name]) throw new Error(`ScamPhrases.kt: section ${name} not found`);
  }
  const out = Object.entries(sections).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 1)};\n`).join('\n');
  writeFileSync(join(web, 'src/engine/phrases.js'), header('android/app/src/main/java/io/cybershield/app/security/ScamPhrases.kt') + out);
  return Object.keys(sections);
}

function decodeAndroid(value) {
  let v = value.trim();
  if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1);
  return v
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&amp;/g, '&')
    .replace(/\\n/g, '\n').replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\@/g, '@').replace(/\\\\/g, '\\');
}

function strings() {
  const result = {};
  for (const [lang, dir] of [['en', 'values'], ['hi', 'values-hi'], ['mr', 'values-mr']]) {
    const xml = readFileSync(join(android, 'res', dir, 'strings.xml'), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
    const table = {};
    for (const m of xml.matchAll(/<string name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/string>/g)) table[m[1]] = decodeAndroid(m[2]);
    for (const m of xml.matchAll(/<plurals name="([a-z0-9_]+)"[^>]*>([\s\S]*?)<\/plurals>/g)) {
      for (const item of m[2].matchAll(/<item quantity="(\w+)">([\s\S]*?)<\/item>/g)) table[`${m[1]}#${item[1]}`] = decodeAndroid(item[2]);
    }
    result[lang] = table;
  }
  writeFileSync(join(web, 'src/strings.js'), header('android/app/src/main/res/values*/strings.xml') + `export const appStrings = ${JSON.stringify(result, null, 1)};\n`);
  return Object.fromEntries(Object.entries(result).map(([k, v]) => [k, Object.keys(v).length]));
}

console.log('phrases.js sections:', phrases().join(', '));
console.log('strings.js entries:', strings());
