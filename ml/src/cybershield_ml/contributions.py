"""Ingest opt-in, redacted contributions into the real training/holdout corpus.

Input: JSONL as written by the backend (see backend/src/contribute.js), one object per line:
    {"id","ts","label","language","kind","findings","text"}

Output: two TSVs in the eval format (id, label, lang, text) — a dev split that may be trained on and a
FROZEN holdout split. Split assignment is deterministic from the record id (a content hash), so a given
sample always lands in the same split across runs: the holdout stays untouched as the corpus grows,
which is what makes it an honest estimate (docs/AI_ML_PLAN.md phases 2-3).
"""
from __future__ import annotations

import hashlib
import json
import re

# Mirrors backend/src/validate.js looksUnredacted: defence in depth, never ingest raw personal data.
_EMAIL = re.compile(r"[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}", re.I)
_PHONE = re.compile(r"(?<!\d)(?:\+?91[ -]?)?[6-9]\d{4}[ -]?\d{5}(?!\d)")
_LONG_DIGITS = re.compile(r"\d{5,}")

_VALID_LABELS = {"scam", "legit"}  # "unsure" is collected but excluded from the labelled corpus
_LANGS = {"en", "hi", "mr", "hinglish", "mixed", "unknown"}


def looks_unredacted(text: str) -> bool:
    return bool(_EMAIL.search(text) or _PHONE.search(text) or _LONG_DIGITS.search(text))


def split_for(record_id: str, holdout_pct: int) -> str:
    """Deterministic, frozen split from the record id. Same id -> same split, always."""
    bucket = int(hashlib.sha1(record_id.encode("utf-8")).hexdigest(), 16) % 100
    return "holdout" if bucket < holdout_pct else "dev"


def ingest(lines, holdout_pct: int):
    """Returns (dev_rows, holdout_rows, skipped). Rows are (id, label, lang, text). Dedups by id."""
    seen: set[str] = set()
    dev: list[tuple[str, str, str, str]] = []
    holdout: list[tuple[str, str, str, str]] = []
    skipped = 0
    for raw in lines:
        raw = raw.strip()
        if not raw:
            continue
        try:
            rec = json.loads(raw)
        except json.JSONDecodeError:
            skipped += 1
            continue
        rid = str(rec.get("id", ""))
        text = str(rec.get("text", "")).strip()
        label = rec.get("label")
        lang = rec.get("language", "unknown")
        if (
            not rid or not text or label not in _VALID_LABELS or lang not in _LANGS
            or rec.get("kind", "message") != "message" or rid in seen or looks_unredacted(text)
        ):
            skipped += 1
            continue
        seen.add(rid)
        row = (rid, label, lang, text.replace("\n", "\\n"))
        (holdout if split_for(rid, holdout_pct) == "holdout" else dev).append(row)
    return dev, holdout, skipped


def write_tsv(path, rows, split_name: str) -> None:
    header = [
        f"# Real, consented, redacted contributions ({split_name} split). GENERATED by",
        "# cybershield_ml.contributions from backend contribution JSONL. Do not edit by hand.",
        "# The holdout split is frozen (deterministic by record id) and must never be trained on.",
        "# Columns: id, label (scam|legit), language, text. \"\\n\" in text means a line break.",
        "id\tlabel\tlang\ttext",
    ]
    body = [f"{rid}\t{label}\t{lang}\t{text}" for (rid, label, lang, text) in rows]
    path.write_text("\n".join(header + body) + "\n", encoding="utf-8")
